/**
 * بوابة الادعاءات (إلزامية قبل النشر) — تعمل على dist/.
 *
 * تمنع شحن ادعاء غير مؤكد في src/config/trust.ts (ترخيص، ضمان، 24/7، نفس اليوم...)،
 * وأي سعر/«يبدأ من»/«أرخص» ما لم يوجد src/config/pricing.ts بأسعار حقيقية.
 *
 * درسان من موقع حقيقي (siteAT.net):
 *   • المولّد يكتب «يضمن لك…» و«الأفضل» و«تأكيد فوري» من تلقاء نفسه، ولا يمسكها أي فاحص بنية.
 *   • النفي يجب أن يُحسب، وإلا صار الفاحص يمنع «لا نضمن نتيجة» وهي جملة صحيحة.
 *     و`\b` لا تعمل مع العربية في JavaScript — لذا النفي هنا بمسافات لا بحدود كلمات.
 * يخرج برمز 1 عند وجود ادعاء مخالف. `--fix-guarantees` يليّن «يضمن/نضمن» في المقالات تلقائيًا.
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join, basename } from 'node:path';
const PRICE_ALLOWED = new Set(['transplant-cost', 'liver-transplant-turkey', 'kidney-transplant-turkey']);

const trustSrc = existsSync('src/config/trust.ts') ? readFileSync('src/config/trust.ts', 'utf8') : '';
// الاسم المفهوميّ بادئةً لا مطابقةً تامّة: `licensedGuidesAvailable` إقرارٌ
// بالترخيص كما `licensed`. ومُلاحقة الأسماء الحرفية تُسقط إقرارات موقَّعة.
const flag = (k) => new RegExp(`^\\s*${k}[A-Za-z]*:\\s*true`, 'm').test(trustSrc);
/**
 * السعر يُكتشف بإعلانه لا باسم ملفّه ولا بموضعه.
 *
 * وُسّعت قائمة الأسماء ثلاث مرّات (pricing ثمّ product ثمّ site ثمّ payments) وكلّ
 * مرّة ظهر مستودع يكتبه في ملفّ آخر — فمُلاحقة الأسماء هي الخطأ. يُقرأ مجلّد الإعداد
 * كلّه، ويُبحث عن مفتاح سعرٍ يليه رقم. وتبقى القاعدة فاعلة على مواقع الخدمات التي
 * تُسعّر لكل مشروع، لأنّها لا تحوي تصريحًا كهذا أصلًا.
 */
// السعر المُعلَن يُعرف بشكله لا باسم حقله: حقلٌ اسمه price/amount، أو أيّ قيمة
// نصّية في ملفّ إعداد تحمل رقمًا تتبعه عملة — وهذا شكل جدول الأسعار مهما سُمّي.
const DECLARED_PRICE = /\b(price|amount)[A-Za-z]*\s*:\s*[^,;\n]*[0-9]|['"][^'"\n]*\d[\d,.]*\s*(دينار|دولار|ريال|درهم|جنيه|شيكل|JOD|JD|SAR|AED|EGP|USD|\$)/;
const hasPricing = (() => {
  const dir = 'src/config';
  if (!existsSync(dir)) return false;
  return readdirSync(dir)
    .filter((f) => f.endsWith('.ts'))
    .some((f) => DECLARED_PRICE.test(readFileSync(dir + '/' + f, 'utf8')));
})();

const RULES = [
  !flag('licensed') && { name: 'ترخيص غير مؤكد', re: /(مرخّ?ص(ون|ين|ة)?|معتمد(ون|ين)? من (وزارة|هيئة|الجهات))/ },
  !flag('guarantee') && { name: 'ضمان', re: /((?<![يتم])[يت]ضمن|نضمن|ضمان (كامل|100|النتيجة|التصدر)|نتائج مضمونة|مضمون(ة)? 100)/ },
  !flag('available247') && { name: '24/7', re: /(24\s*\/\s*7|على مدار الساعة|طوال 24 ساعة)/ },
  !flag('sameDay') && { name: 'نفس اليوم', re: /(في نفس اليوم|تأكيد فوري|حجز فوري|سعر فوري)/ },
  { name: 'تفضيل غير مثبت', re: /(الأفضل في (الأردن|السعودية|الخليج|الوطن العربي|مصر)|(رقم 1|الرقم 1|رقم واحد) في (الأردن|السعودية|مصر|الخليج|الوطن العربي|المنطقة|السوق|المجال)|الأكبر في (الأردن|السعودية|المنطقة))/ },
  !hasPricing && { name: 'سعر', re: /(\d[\d,.]*\s?(دينار|دولار|ريال|درهم|جنيه|JOD|JD|SAR|USD|\$)|(يبدأ|تبدأ|ابتداءً) من\s*\d|(?<![\p{L}])أرخص سعر|(?<![\p{L}])أفضل سعر)/u },
].filter(Boolean);
const NEG = /(كيف نضمن|كيف تضمن|كيف يضمن|لا |ليس|لسنا|لن |دون |بدون|غير |احذر|تجنّ?ب|اسأل|تحقق|تأكّ?د|هل |يجب ألا|لا يمكن)/;
/**
 * تحذير دلالي من الادّعاء: الجملة تذكر «ضمان» لتنفيه أو تفضحه لا لتَعِد به.
 * بدونها يرسب المقال الذي يحمي قارئه من النصّابين، ويُغرق الادّعاء الحقيقي بينها.
 */
const WARNS = /(الانتباه|طُ?عم تسويقي|عبارات مثل|عبارة مثل|كلمة مثل|تُستخدم كطُ?عم|يجب الحذر|الحذر من|احذر|احذري|يدّ?عي|تدّ?عي|يزعم|تزعم|مزاعم|يُسوّ?ق|تُسوّ?ق له|ابتعد عن|لا تنخدع|لا تشترِ|وعد سحري|فتحات سحرية|بدلًا من استخدام|بدلاً من استخدام|عبارات جازمة|الصيغة الممنوعة|مديات تقريبية|مدى تقريبي|للاسترشاد|الأخطاء الشائعة|خطأ شائع|مثال ممنوع|الصياغة الخاطئة|صياغة مخالفة|لا تكتب|تجنّ?ب كتابة|مقولة|يروّ?ج|شعار براق|وعود براقة|الوهم|وهمي|زائف|كاذب|خدع|نصب|نصّ?اب|محتال|احتيال|خراف|مزيّ?ف|يستغل|ابتزاز|لا تصدّ?ق|انتبه|علامة تحذير|مستحيل|يُ?منع |محظور|المحظورات|لا يجوز|القيود على|ادّ?عاءات |يعتقد|يظنّ?|يتصوّ?ر|الاعتقاد|اعتقاد شائع|شائع أن|تكذب|يكذب|تعدك|يعدك|وهمًا|وهماً)/;

/**
 * ضبط قاعدتين على غرضهما لا على ألفاظهما.
 *
 * **سعر** تحرس شيئًا واحدًا: ألّا نُعلن **سعرنا نحن** بلا `src/config/pricing.ts`.
 * لكنها كانت تُسقط كل ذكر لمبلغ: أمثلة افتراضية بأرقام **المطعم** («تبيع وجبة بـ50 ريالًا
 * عبر تطبيق يقتطع 25%»)، وأرقام التسعير النفسي، ونطاقات السوق. وهي مادّة تعليمية هي
 * جوهر مقالات التكلفة والميزانية — حذفها يُفرغها.
 *
 * **24/7** تحرس ادّعاء أنّنا متاحون دائمًا. وكانت تُسقط «قائمة تعمل على مدار الساعة»
 * وهي وصف لموقع **العميل** لا لنا.
 *
 * ⚠️ والأخطر من الإيجابية الكاذبة أنّ بوّابة حمراء دائمًا يتعوّد المرء على تجاهلها،
 * فتمرّ معها الادعاءات الحقيقية. الحلّ تضييق الشرط لا رفع القاعدة.
 */
/** نبرة عرض: هذا ما تمنعه القاعدة فعلًا. */
/**
 * نبرة العرض. تضييقان مقصودان على مواقع التداول والأسواق:
 *   • «أفضل سعر متاح/حالي/طلب/شراء/بيع» تعريفُ أمر السوق لا عرضٌ تجاريّ.
 *   • «تبدأ من 0.1%» و«تبدأ من 2x» واقعتان عن رسوم منصّة ورافعتها لا سعرُ خدمتنا.
 * وما تبقّى — «تبدأ من 99 دولارًا» وأخواتها — يبقى محروسًا كما كان.
 */
// العملة شرطٌ بعد «تبدأ من»: الرقم بلا عملة كمّية أو مقاس لا سعر.
const OFFERY = /((يبدأ|تبدأ|ابتداءً) من\s*\d[\d.,]*\s*(?:دينار|دنانير|دولار|دولارًا|ريال|ريالًا|درهم|درهمًا|جنيه|جنيهًا|شيكل|JOD|JD|SAR|AED|EGP|USD|\$)|أرخص سعر|أفضل سعر(?!\s*(متاح|حالي|حاليًا|طلب|شراء|بيع|دخول|خروج|تنفيذ|ممكن|في\s))|باقتنا|أسعارنا|سعرنا|لدينا باقات|نقدّ?م(ها)? بـ?\s*\d)/;
/** ضمير المتكلّم/الخدمة — المبلغ يصير ادّعاءً حين يُنسب إلينا. */
const OURS = /(نحن|لدينا|خدمتنا|خدماتنا|باقة?نا|فريقنا|نتقاضى|رسومنا|اشتراكنا|عرضنا)/;
/** إتاحة منسوبة إلينا — لا «موقعك يعمل على مدار الساعة». */
const OUR_AVAILABILITY = /(نرد|ندعمك|دعمنا|فريقنا|متاحون|نعمل معك|تواصل معنا)/;

const strip = (h) => h.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ');
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : p.endsWith('.html') ? [p] : []; });

/**
 * قاعدة الادّعاء في موضع واحد يقرأه الطرفان.
 *
 * كان للمولّد تعبيرُه الخاصّ عن الضمان وهو أضيق من تعبير البوّابة: يمسك
 * «نضمن لك ربحًا» ولا يمسك «نضمن أن تكون». فيكتبها المولّد، ويُجيزها حارسه،
 * وتمسكها البوّابة بعد الكتابة — فيُليَّن النصّ ثمّ تعيده الجولة التالية.
 * تصليحٌ يُلغى بصمت كلّ دورة، وهو عطب «طرفَا قاعدة واحدة بتعريفين».
 *
 * فصار المنطق هنا وحده، والبوّابة تستعمله كما يستعمله المولّد قبل الكتابة.
 */
function sentenceFault(s) {
  for (const r of RULES) {
      if (!r.re.test(s) || NEG.test(s) || WARNS.test(s)) continue;
      // استثناء ضيّق: مثال افتراضي بأرقام العميل، وليس فيه نبرة عرض
      // مبلغ لا يُعدّ ادّعاءً إلا بنبرة عرض أو بنسبته إلينا
      if (r.name === 'سعر' && !OFFERY.test(s) && !OURS.test(s)) continue;
      // «على مدار الساعة» عن موقع العميل لا عن إتاحتنا
      if (r.name === '24/7' && !OUR_AVAILABILITY.test(s)) continue;
      // «نفس اليوم» ادّعاءٌ حين يُنسب إلينا؛ وفي غير ذلك هو نصيحة للقارئ أو تحذير
      if (r.name === 'نفس اليوم' && !OURS.test(s) && !OUR_AVAILABILITY.test(s)) continue;
      // ذِكر الترخيص في نصيحة بطلب مختصّ مرخّص ليس ادّعاءً لنا
      if (r.name === 'ترخيص غير مؤكد' && !OURS.test(s)) continue;
      // الموصوف بالترخيص مؤسّسة أو لجنة أو وثيقة — وصفٌ لجهة ثالثة لا ادّعاءٌ عنّا
      if (r.name === 'ترخيص غير مؤكد' &&
          /(ال)?(مستشفيات|مستشفى|مراكز|مركز|جهات|جهة|لجان|لجنة|مختبرات|مختبر|منشآت|منشأة|وثائق|تأشيرات|مؤسسات|مؤسسة|مكاتب|مكتب|شركات|شركة|وكالات|وكالة)(\s+\S+){0,3}\s+[وفبك]?(ال)?(مرخّ?ص|معتمد)/.test(s))
        continue;
      // الضمان المحدود يحصر الوعد فيما نملكه — وهو المطلوب لا الممنوع
      if (r.name === 'ضمان' && /ما نضمنه(\s+\S+){0,3}\s+هو|نضمن لك فقط|لا نضمن/.test(s)) continue;
      // «لضمان كذا» بعد نفي أو تهوين وصفٌ لاعتقاد يُفنَّد لا وعدٌ به؛ ويبقى «نضمن» ممنوعًا
      if (r.name === 'ضمان' &&
          /(لم يعد|لم تعد|لا يكفي|ليس مجرد|ليست مجرد|مجرد)[^.]{0,140}ضمان/.test(s) &&
          !/نضمن/.test(s))
        continue;
      // «الضمان» بمعنى الوديعة المالية لا الوعد بنتيجة — إشارته مفردات الوديعة
      if (r.name === 'ضمان' &&
          /(مبلغ الضمان|الضمان \(الوديعة\)|وديعة|الوديعة|الديبوزيت|يُ?سترَ?دّ?|يُ?صرف مبلغ|تأمين مسترد)/.test(s))
        continue;
      // «يضمن لك» بفاعل غير ضمير المتكلّم وصفٌ لأثر ميزة تقنية لا وعدٌ منّا
      // («تعدّد الجودات يضمن لك الاستمرار»). ويبقى «نضمن» وصيغ الإطلاق ممنوعةً بلا شرط،
      // تمامًا كما تُضيَّق قواعد السعر والترخيص بنسبة الادّعاء إلينا.
      // الإعفاء بالفاعل لا يمتدّ إلى الموعود به: الترتيب والربح والنتيجة ليست
      // «أثر ميزة» مهما كان فاعل الجملة. «الاستثمار … يضمن أن يظهر مطعمك في
      // القائمة الأولى دائمًا» وعدٌ بترتيب، وفاعلُه «الاستثمار» لا يُغيّر ذلك.
      const RANK_PROMISE = /[يت]ضمن[^.؟!]{0,60}(التصدّ?ر|تصدّ?ر|المركز الأول|المرتبة الأولى|القائمة الأولى|الصفحة الأولى|أعلى النتائج|صدارة|الترتيب الطبيعي|ترتيب(ك|ه|ها)? في|ترتيب (موقع|صفح|المواقع)|ربح|أرباح|عائد|دخل|زيارات|عملاء)/;
      if (r.name === 'ضمان' && !/نضمن|ضمان (كامل|100|النتيجة|التصدر)|نتائج مضمونة|مضمون(ة)? 100/.test(s) && !(OURS.test(s) && /[يت]ضمنs+لك/.test(s)) && !RANK_PROMISE.test(s)) continue;
    return r.name;
  }
  return null;
}

/** نصٌّ كامل: اسم أوّل قاعدة تخالفها إحدى جمله، أو `null`. */
export function claimFault(text) {
  for (const s of String(text).split(/(?<=[.!؟?])\s+/)) {
    const name = sentenceFault(s);
    if (name) return name;
  }
  return null;
}

// الاستيراد لا يُشغّل الفحص: جانب سطر الأوامر محروس بهذا وحده. ولا يُفترض
// التشغيل عند غياب argv[1] (‏node -e‎) — غيابه يعني أنّ أحدًا لم يطلب الفحص.
const IS_CLI = process.argv[1] ? import.meta.url === pathToFileURL(process.argv[1]).href : false;

if (IS_CLI && process.argv.includes('--fix-guarantees')) {
  const dir = 'src/content/articles';
  let n = 0;
  for (const f of existsSync(dir) ? readdirSync(dir).filter((x) => x.endsWith('.md')) : []) {
    const p = join(dir, f); const t = readFileSync(p, 'utf8');
    const o = t.replace(/(^|[\s(*])(و?)يضمن لك/gm, '$1$2يتيح لك').replace(/(^|[\s(*])(و?)يضمن /gm, '$1$2يساعد على ').replace(/(^|[\s(*])(و?)نضمن لك/gm, '$1$2نساعدك على').replace(/(^|[\s(*])(و?)نضمن /gm, '$1$2نعمل على ');
    if (o !== t) { writeFileSync(p, o); n++; }
  }
  console.log(`✓ لُيّنت الضمانات في ${n} مقال — أعد البناء ثم شغّل الفحص مجددًا`);
  process.exit(0);
}

if (IS_CLI && !existsSync('dist')) { console.error('✗ لا يوجد dist/ — ابنِ أولًا'); process.exit(1); }
const errors = [];
for (const f of IS_CLI ? walk('dist') : []) {
  const main = readFileSync(f, 'utf8').match(/<main[\s\S]*?<\/main>/)?.[0];
  if (!main) continue;
  for (const s of strip(main).split(/(?<=[.!؟?])\s+/)) {
    const name = sentenceFault(s);
    // TransplantBridge: سعر منقول عن جهة نشرته برصد مؤرّخ، في الصفحات المسموح لها فقط (نفس قاعدة audit.mjs)
    if (name === 'سعر' && PRICE_ALLOWED.has(basename(f, '.html')) && /رُصد/.test(s)) continue;
    if (name) errors.push(`${f.replace(/\\/g, '/').replace(/^dist/, '')} [${name}] «${s.trim().slice(0, 120)}»`);
  }
}
if (IS_CLI) {
  for (const e of errors.slice(0, 60)) console.log('  ✗', e);
console.log(errors.length ? `✗ ${errors.length} ادعاء مخالف — صحّح النص أو أكّد الادعاء في src/config/trust.ts (بعد سؤال صاحب النشاط)` : `✓ لا ادعاءات غير مؤكدة (${RULES.length} قاعدة)`);
  process.exit(errors.length ? 1 : 0);
}

/**
 * حارس: H1 كل صفحة يجب أن يحتوي عبارة البحث الأساسية المعلنة لها.
 *
 * ═══ الخلل الذي أوجد هذا الفاحص ═══
 * الرئيسية تستهدف «كيف أثير زوجي» — بصيغة المتكلّم، لأن هذا ما تكتبه الباحثة فعلًا.
 * وكان H1 فيها «كيف تثيرين زوجك وتزيدين الانجذاب بينكما؟» — بصيغة المخاطَبة.
 * «أثير» و«تثيرين» فعلان مختلفان في العربية، فالعبارة المستهدفة **غائبة تمامًا** عن
 * أقوى عنصر في الصفحة.
 *
 * ولم يكن سهوًا مفردًا بل خللًا بنيويًا: في `content-plan/topics.mjs` حقل `kw` عنوان
 * تحريري و`kw2` عبارات البحث، والمولّد يكتب `title: s.kw` والقالب يشتقّ H1 من `title`
 * — فلا شيء في السلسلة كلها يفرض التقاء العنوان بعبارة البحث. القياس عند الاكتشاف:
 * **63 صفحة من 74 بفجوة**، منها 18 بتغطية ≤ 0.33 وواحدة بصفر.
 *
 * ═══ لماذا يعمل على `dist/` لا على المصدر ═══
 * كي يغطّي **كل** صفحة تلقائيًا — مقالات وصفحات ثابتة وصفحة بيع وأي صفحة تُضاف لاحقًا —
 * بلا قائمة يدوية تُنسى. `BaseHead` يُصدّر `<meta name="keywords">` في كل صفحة، فالمصدر
 * الوحيد للحقيقة موجود في الناتج نفسه. نسخة سابقة كانت تقرأ frontmatter المقالات فقط
 * وتفحص الرئيسية بحالة خاصة مكتوبة يدويًا — أي أن `/kharita/` و`/articles/` وكل صفحة
 * جديدة كانت تفلت منها بصمت.
 *
 * ═══ القاعدة ═══
 * عبارة البحث الأساسية = **أول عنصر في `<meta name="keywords">`**. يجب أن تظهر كل
 * كلماتها الدلالية داخل H1. المقارنة بجذر تقريبي لا بالحرف، فـ«الزوجين» تغطّي «الزوج»
 * و«إثارة» تغطّي «الإثارة» — وإلّا رسبت عناوين سليمة بسبب أل التعريف والتصريف.
 *
 * تُستثنى الصفحات القانونية/الخدمية (`EXEMPT`) لأن نيّتها ملاحية لا بحثية، وكل استثناء
 * مكتوب بسببه: الاستثناء الصامت هو ما يعيد الثغرة أصلًا.
 *
 * ⚠️ لا يقيس هذا الفاحص طول العنوان (`check-title-lengths` يملكه) ولا وجود H1 واحد
 * (`audit-pages` يملكه). يملك **التقاء H1 بعبارة البحث** وحده.
 */
import { readdirSync, readFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';
/**
 * TransplantBridge: لا `<meta name="keywords">` هنا (Google يتجاهلها، فلا نضيفها لإرضاء فاحص).
 * الكلمة الأساسية لكل صفحة = أول مدخلة لها في KEYWORD_MAP، وهي الخريطة نفسها التي
 * يفرضها index.ts عند البناء. فالمصدر واحد ولا تعريفان لقاعدة واحدة.
 */
import { KEYWORD_MAP } from '../src/content/keywords.ts';
const PRIMARY = new Map();
for (const [kw, slug] of KEYWORD_MAP) if (!PRIMARY.has(slug)) PRIMARY.set(slug, kw);

const DIST = 'dist';

/** صفحات نيّتها ملاحية لا بحثية — لا معنى لفرض عبارة بحث في عناوينها. */
const EXEMPT = [
  { re: /^\/404\/?$/, why: 'صفحة خطأ' },
  { re: /^\/privacy-policy\/?$/, why: 'صفحة قانونية' },
  { re: /^\/terms\/?$/, why: 'صفحة قانونية' },
  { re: /^\/contact\/?$/, why: 'صفحة تواصل' },
  { re: /^\/thanks\/?$/, why: 'صفحة ما بعد الدفع (غير مفهرسة)' },
  // صفحات نيّتها ملاحية: `keywords[0]` فيها وسم تصنيف («من نحن»، «أسئلة شائعة»، «مقالات …»)
  // لا عبارة بحث تنافسية. فرض ظهورها في H1 يولّد ضجيجًا يُدرّب على تجاهل الحارس،
  // وتجاهُل الحارس أسوأ من غيابه.
  { re: /^\/about\/?$/, why: 'صفحة تعريفية' },
  { re: /^\/faq\/?$/, why: 'صفحة أسئلة شائعة' },
  { re: /^\/(articles|blog|services|guides)\/?$/, why: 'صفحة فهرس' },
  // [أضِف هنا مسار صفحة المنتج المدفوع للموقع إن وُجد — مثال: { re: /^\/my-product-x7k2\//, why: '...' }]
];

const STOP = new Set([
  'في', 'من', 'على', 'عن', 'مع', 'الى', 'إلى', 'ما', 'هل', 'و', 'او', 'أو',
  'بين', 'لا', 'ان', 'أن', 'هو', 'هي', 'التي', 'الذي', 'كيف', 'بعد', 'قبل',
  'عند', 'هذا', 'هذه', 'كل', 'اي', 'أي',
  // ضمائر العطف والحال — تُقارَن بعد التطبيع (أ→ا). بدونها طلب الحارس ظهور «وهو» حرفيًا
  // في العنوان، فرسب «هل من المناسب بدء التقارب والزوج نائم؟» مقابل «…وهو نائم».
  'وهو', 'وهي', 'وانا', 'انا', 'واحنا', 'احنا', 'ونحن', 'نحن', 'وانت', 'انت',
]);

/** تطبيع عربي — أصناف يونيكود لا `\w` (لاتيني ولا يطابق العربية إطلاقًا). */
const norm = (t) =>
  t
    // ⚠️ الترتيب حسّاس وقد كسرته مرّتين:
    // ١) التشكيل والتطويل **أولًا**: علامات التشكيل العربية Mn وليست \p{L}،
    //    فلو سبقها استبدال الرموز بمسافة لانشطرت «المنظّمة» إلى «المنظ مه».
    // ٢) ثم الرموز، **قبل** NFKC: فـNFKC يوسّع رموز التوافق إلى حروف،
    //    فتصير «زوجك™» = «زوجكtm» ولا تطابق «زوجك».
    .replace(/[\u064B-\u0652\u0640]/g, '')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .normalize('NFKC')
    // توحيد الحالة إلزامي: بدونه «RFP Response Software» لا تطابق «RFP response
    // software» فتُقاس المواقع الإنجليزية كأنها مكسورة بالكامل (قِيست 100% فجوة
    // على خمسة مواقع، وكان العطل في المقياس لا فيها).
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();

/**
 * أداة التعريف فقط — **بلا اقتطاع لواحق**.
 *
 * اقتطاع اللواحق كان يفرط: «ثواني» ← «ثوا» بينما «ثوانٍ» ← «ثوان»، فيفشل التطابق بين
 * صورتين للكلمة نفسها. واللاحقة تُترك للمقارنة بالبادئة في `wordMatches` وهي أدقّ:
 * «ثواني» تبدأ بـ«ثوان»، و«حسابات» تبدأ بـ«حساب». أمّا أداة التعريف فتُزال هنا لأنها
 * **بادئة** تكسر مقارنة البادئة نفسها («المقتطفات» لا تبدأ بـ«مقتطفات»).
 */
const stem = (w) => w.replace(/^(ال|بال|فال|كال|وال|لل)/, '');

const content = (t) => norm(t).split(' ').filter((w) => w && !STOP.has(w)).map(stem);

/**
 * مطابقة بالبادئة لا بالجذر التامّ.
 *
 * التجذير العربي التقريبي يفرط في الاقتطاع: لاحقة «ني» حوّلت «ثواني» إلى «ثوا»
 * بينما «ثوانٍ» بقيت «ثوان»، فبلّغ الفاحص عن فجوة في عنوان سليم تمامًا. والحال نفسه
 * في «حسابات/حساب» و«المنظّمة/المنظمة».
 * العربية لصيقة اللواحق والبادئات لكنها تحفظ البادئة، فمشاركة بادئة بطول ≥4 محارف
 * مؤشّر أدقّ من جذر مخترَع. والتساهل هنا مقصود: حارس يرفع إنذارًا كاذبًا يُدرَّب المرء
 * على تجاهله، فيفوته الإنذار الحقيقي.
 */
function wordMatches(a, b) {
  if (a === b) return true;
  const [s, l] = a.length <= b.length ? [a, b] : [b, a];
  if (s.length >= 4 && l.startsWith(s)) return true;
  // حرف عطف/جرّ ملتصق («وملخّصات»، «بجافاسكربت») بادئة نحوية لا جزء من الكلمة: بدونه
  // رسب H1 «السيو وملخّصات الذكاء الاصطناعي» على «ملخصات الذكاء الاصطناعي» وهو يحويها.
  if (s.length >= 4 && /^[وفبلك]/.test(l) && l.slice(1).startsWith(s)) return true;
  // جمع التكسير يكسر مقارنة البادئة: «حادث ← حوادث» و«كتاب ← كتب». الحروف نفسها
  // بالترتيب مع فارق طول ضئيل مؤشّر أدقّ من جذر مخترَع، وأوّل حرف شرط فلا يشرد.
  if (s.length >= 3 && s[0] === l[0] && l.length - s.length <= 3) {
    let i = 0;
    for (const ch of l) if (ch === s[i]) i++;
    if (i === s.length) return true;
  }
  // المصدر مقابل الفعل المضارع: «شراء ← تشتري». حرف المضارعة يُسقط ثم تُقارن البادئة.
  const bare = (w) => (/^[تينأ]/.test(w) && w.length >= 5 ? w.slice(1) : w);
  const [bs, bl] = [bare(s), bare(l)];
  return bs.length >= 3 && bs[0] === bl[0] && (bl.startsWith(bs) || bs.startsWith(bl));
}

function coverage(title, kw) {
  const have = content(title);
  const want = content(kw);
  if (!want.length) return 1;
  return want.filter((w) => have.some((h) => wordMatches(h, w))).length / want.length;
}

const strip = (h) => h.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (e.endsWith('.html')) out.push(p);
  }
  return out;
}

if (!existsSync(DIST)) {
  console.error(`لا يوجد مجلّد ${DIST} — ابنِ الموقع أولًا (npm run build).`);
  process.exit(1);
}

const files = walk(DIST);
const fails = [];
const exempt = [];
let ok = 0;
let noKw = 0;

for (const f of files) {
  const html = readFileSync(f, 'utf8');
  const url =
    '/' + f.replace(/\\/g, '/').replace(/^dist\//, '').replace(/index\.html$/, '').replace(/\.html$/, '/');

  const skip = EXEMPT.find((x) => x.re.test(url));
  if (skip) { exempt.push({ url, why: skip.why }); continue; }

  const h1m = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
  const primary = PRIMARY.get(url.replace(/^\/|\/$/g, ''));
  if (!h1m || !primary) { noKw++; continue; }

  const h1 = strip(h1m[1]);

  const r = coverage(h1, primary);
  if (r >= 1) { ok++; continue; }
  fails.push({ url, h1, primary, r: r.toFixed(2) });
}

console.log(`صفحات مفحوصة: ${files.length - exempt.length - noKw} (مستثناة ${exempt.length}، بلا كلمات ${noKw})`);
console.log(`✓ H1 يحتوي عبارة البحث الأساسية: ${ok}`);

if (fails.length) {
  console.log(`\n✗ صفحات بفجوة: ${fails.length}`);
  for (const x of fails.sort((a, b) => a.r - b.r)) {
    console.log(`   ${x.r}  ${x.url}`);
    console.log(`      H1     : ${x.h1}`);
    console.log(`      الكلمة : ${x.primary}`);
  }
  console.log('\nالقاعدة: أول كلمة للصفحة في src/content/keywords.ts يجب أن تظهر كاملةً داخل H1.');
  console.log('انتبه لصيغة الفعل: الباحثة تكتب «أثير» لا «تثيرين» — وهما فعلان مختلفان.');
  process.exit(1);
}

console.log('\n✓ كل H1 يلتقي بعبارة بحثه.');
